"""Build the split manifests and the data card from the raw IU X-ray CSV files.

Usage (from the repository root):
  python scripts/prepare_data.py --raw-dir data/raw/iu_xray
  python scripts/prepare_data.py --raw-dir /kaggle/input/chest-xrays-indiana-university \
      --images-dir /kaggle/input/chest-xrays-indiana-university/images/images_normalized

Writes manifests/<partition>/, docs/DATA_CARD.md and data/processed/studies.csv (local cache of the
cleaned text; never committed). With --check, nothing is written: the script only confirms that the
committed manifests are reproduced exactly from the raw files.
"""
import argparse
import csv
import os
import re
import sys
from collections import Counter

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from clinguard.data import clean, labels, manifest, partition, prepare  # noqa: E402

GROUP_ORDER = ["normal", "cardio_pleural", "parenchymal", "other_abnormal"]
REASONS = {"empty_findings": "FINDINGS field is empty",
           "too_short_after_cleaning": "fewer than 5 words after cleaning",
           "no_frontal_image": "no image marked Frontal",
           "image_unreadable": "chosen image does not open"}
WIDER_PRIOR = re.compile(r"\b(comparison|previously|priors|since|redemonstrat\w*|persist\w*|new|now|resolved|"
                         r"improved|improving|worsen\w*|increased|decreased|no change|changed|remains?|still)\b", re.I)


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def partition_tables(rows, assignment, sites):
    cell = Counter((s, r, rows[u]["group"]) for u, (s, r) in assignment.items())
    by_site = []
    for s in sites:
        n = sum(v for (a, _, _), v in cell.items() if a == s)
        g = [sum(cell[(s, r, grp)] for r in partition.ROLES) for grp in GROUP_ORDER]
        by_site.append([s, n] + [f"{x} ({100 * x / n:.0f}%)" for x in g])
    by_role = []
    for s in sites:
        for r in partition.ROLES:
            g = [cell[(s, r, grp)] for grp in GROUP_ORDER]
            prior = sum(rows[u]["needs_prior"] for u, sr in assignment.items() if sr == (s, r))
            by_role.append([s, r, sum(g)] + g + [prior])
    return (md_table(["Site", "Studies"] + GROUP_ORDER, by_site),
            md_table(["Site", "Role", "Studies"] + GROUP_ORDER + ["needs_prior"], by_role))


def data_card(res, manifests, groups_cfg):
    rows, n_total, n_elig = res["rows"], res["n_total"], len(res["rows"])
    groups = Counter(r["group"] for r in rows.values())
    words = sorted(clean.word_count(r["findings"]) for r in rows.values())
    texts = Counter(r["findings"] for r in rows.values())
    n_dup = sum(v for v in texts.values() if v > 1)
    n_prior = sum(r["needs_prior"] for r in rows.values())
    n_wider = sum(1 for r in rows.values() if not r["needs_prior"] and WIDER_PRIOR.search(r["findings"]))
    known = {h for g in groups_cfg["groups"].values() for h in (g or {}).get("headings", [])}
    other_heads = Counter()
    for r in rows.values():
        if r["group"] == "other_abnormal":
            other_heads.update({h for h, _ in labels.parse_mesh(r["mesh"])} - known)
    multi = sum(1 for r in rows.values() if r["n_frontal"] > 1)
    skew_site, skew_role = partition_tables(rows, res["skew"], manifests["skew_v1"]["sites"])
    iid_site, iid_role = partition_tables(rows, res["iid"], manifests["iid_v1"]["sites"])
    image_note = ("All chosen images were opened successfully." if res["meta"]["image_check"] == "passed" else
                  "**not yet run.** The images (14 GB) were not downloaded for this build, so the last rule "
                  "is checked on Kaggle, where the dataset is mounted. If any image fails, that study is "
                  "excluded and the manifests are regenerated before the freeze.")
    n_changed = sum(1 for r in rows.values() if r["masked"])
    excl = [[k, REASONS[k], res["excluded"].get(k, 0)] for k in prepare.EXCLUSION_ORDER]
    return f"""# Data card: IU X-ray for ClinGuard-DiLoCo

Generated by `scripts/prepare_data.py`. Do not edit by hand; rerun the script.

**Status: CANDIDATE, not frozen.** Gate G1 freezes these manifests after the team has reviewed the
counts and the group lists, and after the image check has run.

## Source

- Dataset: {res['meta']['source']}.
- Licence: CC BY-NC-ND 4.0 (as stated on the Kaggle dataset page, checked 2026-11-11). Research use
  only. Raw data, cleaned text and images are never committed or redistributed.
- Raw files: `indiana_reports.csv` ({n_total:,} studies) and `indiana_projections.csv`
  ({res['n_images']:,} images). Their SHA-256 hashes are recorded in every `manifest.json`.
- Versions: cleaning `{res['meta']['clean_version']}`, group lists `{res['meta']['groups_version']}`,
  split seed {res['meta']['split_seed']}.

## Eligibility

A study is excluded for the first rule it fails, in this order (pre-registered, plan section 5.2).

{md_table(["Reason code", "Rule", "Studies excluded"], excl)}

**Eligible studies: {n_elig:,} of {n_total:,}.** The image used is the first Frontal image by filename
order ({multi} eligible studies have more than one frontal image). Lateral images are unused.

Image check: {image_note}

## Text cleaning (`clean_v1`)

- Whitespace is collapsed; casing and punctuation are kept.
- A sentence is removed when more than half of its tokens contain the de-identification mark `XXXX`;
  otherwise the marked tokens are deleted. {n_changed:,} eligible studies ({100 * n_changed / n_elig:.0f}%)
  contained the mark and were changed by this rule.
- **Side effect to review before G1:** deleting a marked word can leave a broken phrase
  ("chronic in.") or strengthen a statement ("No XXXX infiltrates" becomes "No infiltrates", where
  the hidden word may have been "new" or "acute"). The rule is applied as pre-registered.
- Cleaned FINDINGS length: median {words[len(words) // 2]} words, 5th to 95th percentile
  {words[int(0.05 * len(words))]} to {words[int(0.95 * len(words))]}, maximum {words[-1]}.
- **Repeated reports:** {n_dup:,} eligible studies ({100 * n_dup / n_elig:.0f}%) have cleaned FINDINGS text
  identical to at least one other study ({len(texts):,} distinct texts in total). The commonest single
  text occurs {texts.most_common(1)[0][1]} times. These are templated reports for different studies, so
  the same reference text can appear in training and in evaluation splits.
- **`needs_prior`:** {n_prior:,} eligible studies ({100 * n_prior / n_elig:.0f}%) contain one of the fixed
  words ({", ".join(clean.PRIOR_WORDS)}). They stay in every split; results are also reported without
  them. A wider word list (for example "increased", "remains", "persistent", "previously") would flag
  {n_wider} more studies; the list is kept as pre-registered unless the team changes it before G1.

## Partition groups (`groups_v1`)

Decided from the human-coded MeSH field only, first match in this order.

{md_table(["Group", "Studies", "Share"], [[g, groups[g], f"{100 * groups[g] / n_elig:.1f}%"] for g in GROUP_ORDER])}

Commonest MeSH headings among `other_abnormal` studies (a study can carry several), for the team's
review of the group lists: {", ".join(f"{h} ({n})" for h, n in other_heads.most_common(14))}.

## Site partitions

**These are simulated sites from one source, not real hospitals.**

### `skew_v1` (primary)

{skew_site}

{skew_role}

### `iid_v1` (control)

Every study has the same data role as in `skew_v1`; only its site differs.

{iid_site}

{iid_role}

Manifest hashes: `skew_v1` `{manifests['skew_v1']['manifest_hash'][:16]}`, `iid_v1`
`{manifests['iid_v1']['manifest_hash'][:16]}`.

## Limitations

- **No patient identifier.** IU X-ray identifies studies, not patients, so a study is treated as the
  patient unit. Two studies of one patient could fall in different splits; this cannot be checked.
- **Adult-only eligibility cannot be verified**: there is no age field.
- **One source.** All three sites come from the same institution's data. Site differences are created
  by the prevalence table above, not by real differences in scanners, populations or reporting style.
- **Small evaluation splits.** Each site has roughly 100 development and 100 test studies, so per-site
  rates carry wide uncertainty.
- **Group labels are coarse.** One group per study, first match wins; a study with cardiomegaly and
  an opacity counts as `cardio_pleural`.
- **Possible base-model exposure.** IU X-ray is public; a web-trained model may have seen it.
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--raw-dir", required=True, help="folder with indiana_reports.csv and indiana_projections.csv")
    p.add_argument("--images-dir", default=None, help="folder with the PNG images; enables the image-open check")
    p.add_argument("--manifest-dir", default="manifests")
    p.add_argument("--config-dir", default="configs/data")
    p.add_argument("--card", default="docs/DATA_CARD.md")
    p.add_argument("--cache", default="data/processed/studies.csv")
    p.add_argument("--check", action="store_true", help="write nothing; verify the committed manifests are reproduced")
    a = p.parse_args()

    groups_cfg = labels.load_groups(os.path.join(a.config_dir, "groups_v1.yaml"))
    skew_cfg = yaml.safe_load(open(os.path.join(a.config_dir, "skew_v1.yaml")))
    iid_cfg = yaml.safe_load(open(os.path.join(a.config_dir, "iid_v1.yaml")))
    res = prepare.build(a.raw_dir, groups_cfg, skew_cfg, iid_cfg, images_dir=a.images_dir)

    if a.check:
        for name, assignment in (("skew_v1", res["skew"]), ("iid_v1", res["iid"])):
            on_disk = manifest.verify_partition(a.manifest_dir, name)
            if on_disk != assignment:
                sys.exit(f"{name}: committed manifests are NOT reproduced from the raw files")
            print(f"{name}: reproduced exactly ({len(on_disk)} studies)")
        return

    manifests = {name: manifest.write_partition(a.manifest_dir, name, res["rows"], assignment, cfg["sites"], res["meta"])
                 for name, assignment, cfg in (("skew_v1", res["skew"], skew_cfg), ("iid_v1", res["iid"], iid_cfg))}
    os.makedirs(os.path.dirname(a.cache), exist_ok=True)
    with open(a.cache, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["uid", "image", "group", "needs_prior", "findings"])
        for u in sorted(res["rows"], key=int):
            r = res["rows"][u]
            w.writerow([u, r["image"], r["group"], int(r["needs_prior"]), r["findings"]])
    with open(a.card, "w", encoding="utf-8", newline="") as f:
        f.write(data_card(res, manifests, groups_cfg))
    print(f"studies {res['n_total']}  eligible {len(res['rows'])}  excluded {dict(res['excluded'])}")
    for name, m in manifests.items():
        print(name, m["manifest_hash"][:16], {k: v["total"] for k, v in m["counts"].items()})
    print("wrote", a.manifest_dir, a.card, a.cache)


if __name__ == "__main__":
    main()
